# llcomp_fse_groups.py - make llcomp_fse_groups.h (cell -> group maps of the 4-D context) from the calibration CSV
# written by llcomp_q7d.py --e3 --v max3 (<o>_groups.csv: plane, t1, t2, groups, sector 1..49, dcell, level, group, samples).
# usage: python llcomp_fse_groups.py q7d_max3_groups.csv > llcomp_fse_groups.h
import csv, sys
G = {'Y': [None] * 1029, 'UV': [None] * 1029}; th = {}
for r in csv.DictReader(open(sys.argv[1])):
    if int(r['groups']) != 8: continue
    p = 'Y' if r['plane'].startswith('Y') else 'UV'
    cell = ((int(r['sector']) - 1) * 7 + int(r['dcell'])) * 3 + int(r['level'])
    G[p][cell] = int(r['group']); th[p] = (int(r['t1']), int(r['t2']))
assert all(v is not None for p in G for v in G[p]), 'incomplete map'
print('// generated by llcomp_fse_groups.py from %s: cell = (sector * 7 + dcell) * 3 + level -> group 0..7' % sys.argv[1].split('/')[-1])
print('// error-level thresholds (zigzag scale): Y %d %d, U/V %d %d' % (th['Y'] + th['UV']))
print('#pragma once\n#include <cstdint>\nnamespace llcomp_fse {\nstatic const uint8_t kGroups[2][1029] = {')
for p in ('Y', 'UV'):
    v = G[p]; print('  {' + ',\n   '.join(','.join(str(x) for x in v[i:i + 49]) for i in range(0, 1029, 49)) + '},')
print('};\n}')
