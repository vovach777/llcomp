# llcomp_large_cluster.py - static map for llcomp rc -x 4 / -x 5: FFV1-large-like cells (16638 mirrored cells of
# q11(L-TL), q11(TL-T), q11(T-TR), q5(LL-L), q5(TT-T)) -> K clusters, by greedy agglomerative merging of the cells'
# letter histograms (the A31 letters the range coder codes) with the minimal increase of the total code length,
# then a few Lloyd passes (cross-entropy). Unseen cells go to the cluster of the nearest seen cell in q-space.
# Training data: LLC_DUMP=dump.bin llcompc-rc -x 4 img out  (appends 4-byte records: cell u16, letter u8, plane u8)
# usage: python llcomp_large_cluster.py dump.bin [K | Ky,Kuv] > llcomp_large_map.h   (default 256; no dump: placeholder)
import sys, numpy as np
TWO = '--two' in sys.argv; sys.argv = [a for a in sys.argv if a != '--two']   # --two: modes 7/8 (tiny sign, 33275 cells)
NC, NL = (33275 if TWO else 16638), 32
def cells_q():
    i = np.arange(NC); q = []
    for base, m in ((1, 11), (11, 11), (121, 11), (1331, 5), (6655, 5)): pass
    # decode signed mixed radix: idx = q0 + 11 q1 + 121 q2 + 1331 q3 + 6655 q4, q0..q2 in -5..5, q3, q4 in -2..2
    out = np.zeros((NC, 5), int)
    for c in range(NC):
        v = c - (16637 if TWO else 0); r = []
        for m in (11, 11, 11, 5):
            h = m // 2; d = ((v + h) % m) - h; r.append(d); v = (v - d) // m
        r.append(v); out[c] = r
    return out
def code_len(h):  # total code length (bits) of a histogram row-wise
    n = h.sum(-1, keepdims=True); with_ = np.where(h > 0, h * np.log2(np.where(h > 0, n / np.maximum(h, 1), 1)), 0); return with_.sum(-1)
def cluster(H, K):
    seen = np.nonzero(H.sum(1) > 0)[0]; X = H[seen].astype(np.float64); m = len(seen)
    def lloyd(lab, k, it):
        for _ in range(it):
            Q = np.zeros((k, NL)); np.add.at(Q, lab, X); Q = (Q + 0.5) / (Q + 0.5).sum(1, keepdims=True)
            lab = np.argmin(-(X @ np.log2(Q).T), 1)
        return lab
    M0 = max(4 * K, 1024)
    if m > M0:            # stage 1: cross-entropy k-means to M0 clusters, seeded by the M0 most frequent cells
        top = np.argsort(-X.sum(1))[:M0]; lab0 = np.zeros(m, int); lab0[top] = np.arange(M0)
        Q = (X[top] + 0.5) / (X[top] + 0.5).sum(1, keepdims=True); lab0 = np.argmin(-(X @ np.log2(Q).T), 1)
        lab0 = lloyd(lab0, M0, 8); used = np.unique(lab0); remap = {c: t for t, c in enumerate(used)}; lab0 = np.array([remap[c] for c in lab0])
        Xc = np.zeros((len(used), NL)); np.add.at(Xc, lab0, X)
    else: lab0 = np.arange(m); Xc = X
    mc = len(Xc)
    if mc <= K: lab = lab0
    else:                 # stage 2: greedy agglomerative merging with the least code-length increase
        C = Xc.copy(); m2 = mc; alive = np.ones(m2, bool); cl = code_len(C); grp = np.arange(m2)
        # merge cost matrix in chunks
        def row_cost(i):
            M = C + C[i]; return code_len(M) - cl - cl[i]
        cost = np.full((m2, m2), np.inf)
        for i in range(m2): r = row_cost(i); r[i] = np.inf; cost[i] = r
        for step in range(m2 - K):
            k = np.argmin(cost); i, j = divmod(k, m2)
            C[i] += C[j]; alive[j] = False; grp[grp == j] = i; cl[i] = code_len(C[i:i + 1])[0]
            cost[j, :] = np.inf; cost[:, j] = np.inf
            r = row_cost(i); r[~alive] = np.inf; r[i] = np.inf; cost[i] = r; cost[:, i] = r
        ids = {c: t for t, c in enumerate(sorted(set(grp)))}; grp = np.array([ids[c] for c in grp]); lab = grp[lab0]
    lab = lloyd(lab, K, 5)   # final Lloyd: each cell to the cluster with the least cross-entropy
    full = np.zeros(NC, int); full[seen] = lab
    if len(seen) < NC:   # unseen -> nearest seen cell (L1 in q space)
        q = cells_q(); qs = q[seen]
        for c in np.setdiff1d(np.arange(NC), seen): full[c] = lab[np.argmin(np.abs(qs - q[c]).sum(1))]
    Hk = np.array([X[lab == k].sum(0) for k in range(K)]); tot = code_len(Hk).sum() / X.sum()
    return full, tot, code_len(X).sum() / X.sum(), len(seen), Hk
Ks = [int(v) for v in (sys.argv[2] if len(sys.argv) > 2 else '256').split(',')]; Ks = Ks * 2 if len(Ks) == 1 else Ks   # K or Ky,Kuv
maps = [np.arange(NC) % 256, np.arange(NC) % 256]; note = 'identity placeholder (cell % 256)'; hists = [np.ones((256, NL)), np.ones((256, NL))]
if len(sys.argv) > 1 and sys.argv[1] != '-':
    r = np.fromfile(sys.argv[1], np.uint8).reshape(-1, 4); cell = r[:, 0].astype(int) | (r[:, 1].astype(int) << 8); note = '%d samples from %s, K = %s' % (len(r), sys.argv[1], Ks)
    for g in (0, 1):
        sel = r[:, 3] == g
        if not sel.any(): continue
        H = np.zeros((NC, NL), np.int64); np.add.at(H, (cell[sel], r[sel, 2].astype(int)), 1)
        K = Ks[g]; maps[g], tot, raw, ns, hk = cluster(H, K); hists[g] = np.vstack([hk, np.ones((256 - K, NL))])
        print('plane %d: %d seen cells, H(letter|cell) %.4f -> H(letter|cluster) %.4f bits' % (g, ns, raw, tot), file=sys.stderr)
print('// generated by llcomp_large_cluster.py: %s' % note)
print('#pragma once\n#include <cstdint>\nnamespace llcomp_large {\nstatic const uint8_t kLargeMap%s[2][%d] = {' % ('2' if TWO else '', NC))
for g in (0, 1): print('  {' + ','.join(str(int(v)) for v in maps[g]) + '},')
print('};')
# preset CDFs (mode 6): cumulative of the 31 letters per cluster, width >= 2 (the adaptation bounds), total 32768
print('static const uint16_t kLargePreset%s[2][256][32] = {' % ('2' if TWO else ''))
for g in (0, 1):
    print('  {')
    for k in range(256):
        h = hists[g][k][:31] + 0.5; p = h / h.sum(); w = 2 + np.floor(p * (32768 - 62)).astype(int); w[np.argmax(w)] += 32768 - w.sum()
        c = np.concatenate([[0], np.cumsum(w)]); print('   {' + ','.join(str(int(v)) for v in c) + '},')
    print('  },')
print('};\n}')
